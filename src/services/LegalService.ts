/** دریافت یک سند قانونی بر اساس id */
export function getLegalDoc(id: string): LegalDoc | null {
  const docId = id as LegalDocId;
  return DOCS[docId] ?? null;
}

/** دریافت لیست همه‌ی اسناد (برای منو و footer) */
export function getLegalDocs(): LegalDoc[] {
  return Object.values(DOCS);
}